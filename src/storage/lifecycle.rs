//! Bucket lifecycle configuration: rule types (shared by the S3 XML API and
//! the console JSON API), validation, and the expiration engine.
//!
//! The engine is a plain async function over the storage layer with an
//! injected clock (`now`) so it can be tested deterministically. It is run
//! hourly from the housekeeping task in `main.rs`.

use chrono::{DateTime, Duration, NaiveTime, TimeZone, Utc};
use serde::{Deserialize, Serialize};
use utoipa::ToSchema;

use super::filesystem::FilesystemStorage;
use super::{ObjectMeta, StorageError};
use crate::error::{S3Error, S3ErrorCode};

/// Maximum number of rules in one configuration (S3 limit, not adjustable).
pub const MAX_RULES: usize = 1000;
/// Maximum length of a rule ID.
pub const MAX_ID_LEN: usize = 255;
/// `NewerNoncurrentVersions` must be within 1..=100.
pub const MAX_NEWER_NONCURRENT_VERSIONS: u32 = 100;

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
pub enum LifecycleStatus {
    Enabled,
    Disabled,
}

/// One object tag a rule filter requires (key and value must match exactly).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
#[serde(rename_all = "camelCase")]
pub struct LifecycleTag {
    pub key: String,
    #[serde(default)]
    pub value: String,
}

/// Which objects a rule applies to. All set conditions must match (logical
/// AND). An empty filter matches every object in the bucket.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
#[serde(rename_all = "camelCase")]
pub struct LifecycleFilter {
    /// Key prefix; empty matches all keys.
    #[serde(default, skip_serializing_if = "String::is_empty")]
    pub prefix: String,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub tags: Vec<LifecycleTag>,
    /// Only objects strictly larger than this many bytes.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub object_size_greater_than: Option<u64>,
    /// Only objects strictly smaller than this many bytes.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub object_size_less_than: Option<u64>,
    /// The client sent a legacy top-level `<Prefix>` rather than `<Filter>`.
    /// GET echoes that form. Absent (false) means the rule was a Filter, which
    /// is what the AWS CLI, Terraform, and `mc ilm` send.
    #[serde(default, skip_serializing_if = "is_false")]
    #[schema(ignore)]
    pub legacy_prefix: bool,
}

/// Expiration of current object versions (`Days` or `Date`), or removal of
/// expired object delete markers (`ExpiredObjectDeleteMarker`).
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
#[serde(rename_all = "camelCase")]
pub struct LifecycleExpiration {
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub days: Option<u32>,
    /// ISO 8601 date at midnight UTC, e.g. `2030-01-01T00:00:00.000Z`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub date: Option<String>,
    #[serde(default, skip_serializing_if = "is_false")]
    pub expired_object_delete_marker: bool,
}

/// Permanent deletion of noncurrent versions.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
#[serde(rename_all = "camelCase")]
pub struct NoncurrentVersionExpiration {
    /// Days after the version became noncurrent.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub noncurrent_days: Option<u32>,
    /// Number of newest noncurrent versions to retain (1–100).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub newer_noncurrent_versions: Option<u32>,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
#[serde(rename_all = "camelCase")]
pub struct AbortIncompleteMultipartUpload {
    pub days_after_initiation: u32,
}

/// One bucket lifecycle rule (JSON form, camelCase). Stored in
/// `.bucket.json` and used as-is by the console API.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, ToSchema)]
#[serde(rename_all = "camelCase")]
pub struct LifecycleRule {
    /// Unique rule ID (≤255 chars). Empty → generated by `validate_rules`.
    #[serde(default)]
    pub id: String,
    pub status: LifecycleStatus,
    #[serde(default)]
    pub filter: LifecycleFilter,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub expiration: Option<LifecycleExpiration>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub noncurrent_version_expiration: Option<NoncurrentVersionExpiration>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub abort_incomplete_multipart_upload: Option<AbortIncompleteMultipartUpload>,
}

fn is_false(v: &bool) -> bool {
    !*v
}

impl LifecycleRule {
    pub fn is_enabled(&self) -> bool {
        self.status == LifecycleStatus::Enabled
    }
}

impl LifecycleFilter {
    /// Prefix + tags + size bounds against one object version.
    pub fn matches(&self, meta: &ObjectMeta) -> bool {
        if !meta.key.starts_with(&self.prefix) {
            return false;
        }
        if let Some(gt) = self.object_size_greater_than {
            if meta.size <= gt {
                return false;
            }
        }
        if let Some(lt) = self.object_size_less_than {
            if meta.size >= lt {
                return false;
            }
        }
        self.tags.iter().all(|t| {
            meta.tags
                .as_ref()
                .and_then(|tags| tags.get(&t.key))
                .is_some_and(|v| *v == t.value)
        })
    }
}

