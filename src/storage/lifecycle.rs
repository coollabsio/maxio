/// Parse a lifecycle `Date` (ISO 8601). It must be midnight UTC.
pub fn parse_lifecycle_date(s: &str) -> Result<DateTime<Utc>, S3Error> {
    let s = s.trim();
    let parsed = DateTime::parse_from_rfc3339(s)
        .map(|d| d.with_timezone(&Utc))
        .or_else(|_| {
            chrono::NaiveDate::parse_from_str(s, "%Y-%m-%d")
                .map(|d| Utc.from_utc_datetime(&d.and_time(NaiveTime::MIN)))
        })
        .map_err(|_| S3Error::invalid_argument("'Date' must be an ISO 8601 date"))?;
    if parsed.time() != NaiveTime::MIN {
        return Err(S3Error::invalid_argument("'Date' must be at midnight GMT"));
    }
    Ok(parsed)
}

/// Canonical rendering of a lifecycle date (what GET returns).
pub fn format_lifecycle_date(d: &DateTime<Utc>) -> String {
    d.format("%Y-%m-%dT%H:%M:%S%.3fZ").to_string()
}

/// `x-amz-expiration` for an object that matches an enabled expiration rule.
/// The earliest matching expiry wins, matching S3 when several rules apply.
pub fn expiration_header(rules: &[LifecycleRule], meta: &ObjectMeta) -> Option<String> {
    let created = DateTime::parse_from_str(&meta.last_modified, "%Y-%m-%dT%H:%M:%S%.3fZ")
        .or_else(|_| DateTime::parse_from_rfc3339(&meta.last_modified))
        .ok()?
        .with_timezone(&Utc);
    let mut best: Option<(DateTime<Utc>, &str)> = None;
    for rule in rules {
        if !rule.is_enabled() || !rule.filter.matches(meta) {
            continue;
        }
        let Some(exp) = &rule.expiration else {
            continue;
        };
        let when = if let Some(days) = exp.days {
            // One extra second so a timestamp truncated to milliseconds is not
            // earlier than the client's "now", which would make (expiry - now)
            // fall just short of N days.
            created + Duration::days(i64::from(days)) + Duration::seconds(1)
        } else if let Some(date) = &exp.date {
            match parse_lifecycle_date(date) {
                Ok(d) => d,
                Err(_) => continue,
            }
        } else {
            continue;
        };
        match best {
            Some((at, _)) if when >= at => {}
            _ => best = Some((when, rule.id.as_str())),
        }
    }
    let (when, id) = best?;
    let http = when.format("%a, %d %b %Y %H:%M:%S GMT");
    Some(format!("expiry-date=\"{http}\", rule-id=\"{id}\""))
}

/// Validate a full configuration the way S3 does, generate missing rule IDs
/// and normalize dates.
pub fn validate_rules(rules: &mut [LifecycleRule]) -> Result<(), S3Error> {
    if rules.is_empty() {
        return Err(S3Error::new(
            S3ErrorCode::MalformedXML,
            "The lifecycle configuration must contain at least one rule",
        ));
    }
    if rules.len() > MAX_RULES {
        return Err(S3Error::new(
            S3ErrorCode::MalformedXML,
            format!("A lifecycle configuration can have at most {MAX_RULES} rules"),
        ));
    }
    let mut seen = std::collections::HashSet::new();
    for rule in rules.iter_mut() {
        if rule.id.is_empty() {
            rule.id = uuid::Uuid::new_v4().simple().to_string();
        }
        if rule.id.chars().count() > MAX_ID_LEN {
            return Err(S3Error::invalid_argument(
                "ID length should not exceed allowed limit of 255",
            ));
        }
        if !seen.insert(rule.id.clone()) {
            return Err(S3Error::invalid_argument(
                "Rule ID must be unique. Found same ID for more than one rule",
            ));
        }

        let f = &rule.filter;
        if let (Some(gt), Some(lt)) = (f.object_size_greater_than, f.object_size_less_than) {
            if gt >= lt {
                return Err(S3Error::invalid_request(
                    "ObjectSizeGreaterThan must be less than ObjectSizeLessThan",
                ));
            }
        }
        // Filter tags follow the object tag rules, reported as InvalidRequest
        // (what S3 returns for duplicate keys).
        super::validate_tags(
            f.tags.iter().map(|t| (t.key.as_str(), t.value.as_str())),
            usize::MAX,
            false,
        )
        .map_err(|e| S3Error::invalid_request(&e.message))?;
        let has_tags = !f.tags.is_empty();

        let mut has_action = false;
        if let Some(exp) = rule.expiration.as_mut() {
            if exp.days.is_some() && exp.date.is_some() {
                return Err(S3Error::new(
                    S3ErrorCode::MalformedXML,
                    "Expiration cannot specify both Days and Date",
                ));
            }
            if exp.expired_object_delete_marker && (exp.days.is_some() || exp.date.is_some()) {
                return Err(S3Error::new(
                    S3ErrorCode::MalformedXML,
                    "ExpiredObjectDeleteMarker cannot be specified with Days or Date in a \
                     Lifecycle Expiration Policy",
                ));
            }
            if exp.days == Some(0) {
                return Err(S3Error::invalid_argument(
                    "'Days' for Expiration action must be a positive integer",
                ));
            }
            if let Some(date) = exp.date.as_ref() {
                exp.date = Some(format_lifecycle_date(&parse_lifecycle_date(date)?));
            }
            if exp.expired_object_delete_marker && has_tags {
                return Err(S3Error::invalid_request(
                    "ExpiredObjectDeleteMarker cannot be specified with a tag-based filter",
                ));
            }
            has_action |= exp.days.is_some() || exp.date.is_some();
            has_action |= exp.expired_object_delete_marker;
        }
        if let Some(nve) = rule.noncurrent_version_expiration.as_ref() {
            if nve.noncurrent_days.is_none() && nve.newer_noncurrent_versions.is_none() {
                return Err(S3Error::new(
                    S3ErrorCode::MalformedXML,
                    "NoncurrentVersionExpiration requires NoncurrentDays",
                ));
            }
            if nve.noncurrent_days == Some(0) {
                return Err(S3Error::invalid_argument(
                    "'NoncurrentDays' for NoncurrentVersionExpiration action must be a positive integer",
                ));
            }
            if let Some(n) = nve.newer_noncurrent_versions {
                if n == 0 || n > MAX_NEWER_NONCURRENT_VERSIONS {
                    return Err(S3Error::invalid_argument(
                        "'NewerNoncurrentVersions' must be between 1 and 100",
                    ));
                }
            }
            has_action = true;
        }
        if let Some(abort) = rule.abort_incomplete_multipart_upload.as_ref() {
            if abort.days_after_initiation == 0 {
                return Err(S3Error::invalid_argument(
                    "'DaysAfterInitiation' for AbortIncompleteMultipartUpload action must be a positive integer",
                ));
            }
            if has_tags {
                return Err(S3Error::invalid_request(
                    "AbortIncompleteMultipartUpload cannot be specified with Tags",
                ));
            }
            has_action = true;
        }
        if !has_action {
            return Err(S3Error::invalid_request(
                "At least one action needs to be specified in a rule",
            ));
        }
    }
    Ok(())
}

